import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { publishedPortfolio } from "../src/portfolio/content-policy.mjs";
import { compile } from "json-schema-to-typescript";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

export async function prepareContract(root = projectRoot, candidate) {
  const schemaPath = path.join(root, "portfolio.schema.json");
  const configPath = path.join(root, "portfolio.json");
  const typePath = path.join(root, "src", "portfolio", "schema.generated.ts");
  const configOutputPath = path.join(
    root,
    "src",
    "portfolio",
    "config.generated.ts",
  );
  const validatorPath = path.join(
    root,
    "src",
    "portfolio",
    "portfolio-validator.cjs",
  );
  const declarationPath = path.join(
    root,
    "src",
    "portfolio",
    "portfolio-validator.d.cts",
  );

  const schema = JSON.parse(await fs.readFile(schemaPath, "utf8"));
  const portfolio =
    candidate ?? JSON.parse(await fs.readFile(configPath, "utf8"));
  const typeSchema = structuredClone(schema);
  delete typeSchema.title;

  const generatedTypes = await compile(typeSchema, "PortfolioConfig", {
    bannerComment:
      "// Generated from portfolio.schema.json by scripts/generate-portfolio-contract.mjs.\n// Do not edit this file directly.",
    unreachableDefinitions: true,
    style: { singleQuote: false },
  });

  const ajv = new Ajv2020({
    allErrors: true,
    strict: false,
    validateFormats: false,
    code: { source: true },
  });
  const validate = ajv.compile(schema);
  if (!validate(portfolio))
    throw new Error(`Invalid portfolio: ${JSON.stringify(validate.errors)}`);
  const generatedValidator = `/* eslint-disable */\n${standaloneCode(ajv, validate).trimEnd()}\n`;
  const generatedDeclaration = `// Generated with the runtime validator. Do not edit directly.\nimport type { ErrorObject } from "ajv";\nimport type { PortfolioConfig } from "./schema.generated";\n\ndeclare function validatePortfolio(data: unknown): data is PortfolioConfig;\ndeclare namespace validatePortfolio {\n  let errors: ErrorObject[] | null | undefined;\n}\nexport = validatePortfolio;\n`;
  const generatedConfig = `// Generated from portfolio.json by scripts/generate-portfolio-contract.mjs.\n// Do not edit this file directly.\nimport type { PortfolioConfig } from "./schema.generated";\n\nconst portfolio = ${JSON.stringify(publishedPortfolio(portfolio), null, 2)} satisfies PortfolioConfig;\n\nexport default portfolio;\n`;

  const outputs = [
    [typePath, generatedTypes],
    [configOutputPath, generatedConfig],
    [validatorPath, generatedValidator],
    [declarationPath, generatedDeclaration],
  ];

  return outputs;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const outputs = await prepareContract();
  const stale = [];
  for (const [target, expected] of outputs) {
    const current = await fs.readFile(target, "utf8").catch(() => "");
    if (current.replaceAll("\r\n", "\n") !== expected.replaceAll("\r\n", "\n"))
      stale.push(path.relative(projectRoot, target));
  }
  if (stale.length) {
    console.error(
      "Generated contract is stale: " +
        stale.join(", ") +
        ". Run npm run content:build.",
    );
    process.exitCode = 1;
  } else console.log("Generated portfolio contract is current.");
}
